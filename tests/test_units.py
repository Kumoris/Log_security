def test_commit_message_with_separator_bytes(tmp_path):
    import subprocess
    from src.repo.history import all_commits, first_parent_log
    r = tmp_path / "r"
    r.mkdir()
    run = lambda *a: subprocess.run(["git", "-C", str(r), *a], check=True, capture_output=True,
                                    env={"GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@x", "GIT_COMMITTER_NAME": "t",
                                         "GIT_COMMITTER_EMAIL": "t@x", "PATH": "/usr/bin:/bin"})
    run("init", "-q", "-b", "main")
    (r / "a.py").write_text("x = 1\n")
    run("add", "a.py")
    run("commit", "-q", "-m", "weird \x1e record \x1f unit separator")
    (r / "a.py").write_text("x = 2\n")
    run("commit", "-qam", "second (#3)")
    cs = list(all_commits(r, "HEAD"))
    assert len(cs) == 2 and "record" in cs[1].message
    fp = [c for c, _ in first_parent_log(r, "HEAD", with_changes=True)]
    assert [c.message.split("\n")[0] for c in fp][1] == "second (#3)"


