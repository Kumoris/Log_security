HEAD = "import logging\nlog = logging.getLogger(__name__)\n\n"


def logs(src):
    return list(find_logs("a.py", src).statements)


def test_items_and_template():
    (a, b, c, d) = logs(HEAD + "def f(req, token, user):\n"
                               "    if req.debug:\n"
                               "        log.info(f'ok {user.id} {req.email} {token[:6]}')\n"
                               "    log.warning('x %s %s', mask(req.email), user, extra={'uid': user.id}, exc_info=True)\n"
                               "    log.info('a {} {k}'.format(x, k=y))\n"
                               "    print('hi', resp.json())\n")
    assert a.template == "ok {} {} {}" and a.conditions == ("req.debug",)
    assert [(i.expr, i.core, i.wrappers) for i in a.items] == [
        ("user.id", "user.id", ()), ("req.email", "req.email", ()), ("token[:6]", "token", ("slice",))]
    assert [(i.core, i.wrappers, i.key, i.role) for i in b.items] == [
        ("req.email", ("mask",), None, "value"), ("user", (), None, "value"), ("user.id", (), "uid", "value"),
        ("<exc_info>", (), None, "exception")]
    assert [(i.expr, i.key) for i in c.items] == [("x", None), ("y", "k")]
    assert d.sink == "print" and [i.expr for i in d.items] == ["resp.json()"]
    assert logs(HEAD + "print('x')\n") and not find_logs("a.py", HEAD + "print('x')\n", False).statements


def test_match_duplicates_by_position_and_modified():
    a = HEAD + "def f(user):\n    print('done')\n    log.info('login %s', user.email)\n    print('done')\n"
    b = HEAD + "def f(user):\n    x = 1\n    print('done')\n    log.info('login %s', user.id)\n    print('done')\n"
    r = match_file(logs(a), logs(b), hunks_from_texts(a, b))
    kinds = sorted((p.kind, p.before.line, p.after.line) for p in r.pairs)
    assert kinds == [("modified", 6, 7), ("unchanged", 5, 6), ("unchanged", 7, 8)]
    assert not r.added and not r.deleted
    rec = change_record(*[(p.before, p.after) for p in r.pairs if p.kind == "modified"][0])
    assert rec["items_added"] == ["user.id"] and rec["items_removed"] == ["user.email"] and not rec["message_changed"]


def test_match_deleted_added_and_many_to_many():
    a = HEAD + "def f():\n    log.info('one %s', a)\n    log.info('two %s', b)\n"
    b = HEAD + "def f():\n    log.info('two %s', b2)\n    log.info('one %s', a2)\n    log.error('three')\n"
    r = match_file(logs(a), logs(b), hunks_from_texts(a, b))
    pairs = {p.before.template: p.after.template for p in r.pairs}
    assert pairs == {"one %s": "one %s", "two %s": "two %s"}
    assert [s.template for s in r.added] == ["three"]


def test_hungarian_is_optimal_not_greedy():
    # greedy would take (0,0)=0.9 then (1,1)=0.1; optimal is (0,1)+(1,0)=1.6
    assert sorted(hungarian([[0.9, 0.8], [0.8, 0.1]])) == [(0, 1), (1, 0)]


