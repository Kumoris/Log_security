def test_author_three_values_never_human_by_default():
    idx = PrIndex.build([{"number": 7, "agent": "Copilot", "commit_shas": ["a" * 40]}])
    at = datetime(2026, 1, 1, tzinfo=timezone.utc)
    c = lambda sha, msg, name="bob", email="b@x": Commit(sha, (), at, name, email, msg)
    assert attribute(c("a" * 40, "wip"), idx)["evidence"] == "aidev_pr_commit"
    assert attribute(c("b" * 40, "Add x (#7)"), idx)["author_kind"] == "agent"
    assert attribute(c("b" * 40, "Merge pull request #8 from a/b"), idx)["author_kind"] == "not_agent"
    assert attribute(c("b" * 40, "fix\n\nGenerated with [Claude Code]"), idx)["agent"] == "Claude_Code"
    assert attribute(c("b" * 40, "direct push"), idx)["author_kind"] == "unknown"
    assert pr_number_in("Title (#12)\n\nbody (#3)") == 12


def test_features_with_evidence():
    src = ("import logging, os\nfrom pydantic import BaseModel, EmailStr\nlog = logging.getLogger(__name__)\n"
           "class Req(BaseModel):\n    email: EmailStr\n"
           "class S:\n    def __init__(self):\n        self.api_key = os.getenv('OPENAI_API_KEY')\n"
           "    def run(self):\n        log.info('k %s', self.api_key)\n"
           "def f(req: Req, request):\n    token = make_token()\n"
           "    log.info(f'{req.email} {token[:4]} {len(items)}')\n"
           "    log.info('auth %s', request.headers['Authorization'])\n"
           "    log.info('password=hunter2')\n")
    st = {s.line: s for s in find_logs("a.py", src).statements}
    k = identify_statement(st[10], src)[0]
    assert "AUTH.api_key" in k["categories"] and "CFG.environment" in k["categories"]
    email, token, count = identify_statement(st[13], src)
    assert email["categories"] == ["PII.email"] and {e["kind"] for e in email["evidence"]} == {"name", "type"}
    assert token["categories"] == ["AUTH.access_token"] and token["wrappers"] == ["slice"]
    assert count["categories"] == []                              # unclassified, not "safe"
    assert identify_statement(st[14], src)[0]["categories"] == ["AUTH.authorization_header"]
    assert identify_statement(st[15], src)[-1]["role"] == "message"


def test_move_requires_same_message():
    a = HEAD + "def f(fn):\n    log.debug(f'Cache hit for {fn}')\n\n\ndef g():\n    pass\n"
    b = HEAD + "def f(fn):\n    pass\n\n\ndef g(fn):\n    x = 1\n    log.debug(f'Cache miss for {fn}')\n"
    r = match_file(logs(a), logs(b), hunks_from_texts(a, b))
    assert not any(p.kind == "moved" for p in r.pairs)
    c = HEAD + "def f(fn):\n    pass\n\n\ndef g(fn):\n    x = 1\n    log.debug(f'Cache hit for {fn}')\n"
    r = match_file(logs(a), logs(c), hunks_from_texts(a, c))
    assert [p.kind for p in r.pairs] in (["moved"], ["modified"], ["unchanged"])


